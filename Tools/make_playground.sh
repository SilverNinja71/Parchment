#!/bin/zsh
# Builds Playground/Parchment.swiftpm: an App Playground that the free Swift Playgrounds
# app on iPad can open, build and run. No Xcode needed.
#
#   zsh Tools/make_playground.sh
#
# The app's code lives in Parchment/. Edit it there and re-run this script.
set -euo pipefail

ROOT="${0:A:h:h}"
OUT_DIR="$ROOT/Playground"
PACKAGE="$OUT_DIR/Parchment.swiftpm"

rm -rf "$PACKAGE" "$OUT_DIR/Parchment.swiftpm.zip"
mkdir -p "$PACKAGE"

# Swift sources (keeping their folders) and the asset catalog. Info.plist is left out:
# Swift Playgrounds generates its own from Package.swift.
rsync -a --prune-empty-dirs --include='*/' --include='*.swift' --exclude='*' "$ROOT/Parchment/" "$PACKAGE/"
cp -R "$ROOT/Parchment/Assets.xcassets" "$PACKAGE/"

cat > "$PACKAGE/Package.swift" <<'SWIFT'
// swift-tools-version: 5.8

// Generated by Tools/make_playground.sh from the Parchment/ folder.
// Swift Playgrounds may rewrite this file when you change App Settings; that's fine.

import PackageDescription
import AppleProductTypes

let package = Package(
    name: "Parchment",
    platforms: [
        .iOS("17.0")
    ],
    products: [
        .iOSApplication(
            name: "Parchment",
            targets: ["AppModule"],
            bundleIdentifier: "com.example.parchment",
            teamIdentifier: "",
            displayVersion: "1.0",
            bundleVersion: "1",
            appIcon: .asset("AppIcon"),
            accentColor: .asset("AccentColor"),
            supportedDeviceFamilies: [
                .pad
            ],
            supportedInterfaceOrientations: [
                .portrait,
                .landscapeRight,
                .landscapeLeft,
                .portraitUpsideDown(.when(deviceFamilies: [.pad]))
            ]
        )
    ],
    targets: [
        .executableTarget(
            name: "AppModule",
            path: "."
        )
    ]
)
SWIFT

# A zip AirDrops cleanly; on the iPad, tap it in Files to unzip.
(cd "$OUT_DIR" && ditto -c -k --sequesterRsrc --keepParent Parchment.swiftpm Parchment.swiftpm.zip)

echo "Built $PACKAGE ($(find "$PACKAGE" -name '*.swift' ! -name Package.swift | wc -l | tr -d ' ') Swift files)"
echo "Built $OUT_DIR/Parchment.swiftpm.zip ($(du -h "$OUT_DIR/Parchment.swiftpm.zip" | cut -f1))"
